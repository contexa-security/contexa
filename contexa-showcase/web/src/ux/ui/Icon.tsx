export type UxIconName = keyof typeof ICONS;

/** 12 · 14 · 16 · 18 · 20 · 24 px (기획안 6.3: menu 18, cards 16~20, figure chips 20). */
export type IconSize = 'xs' | 'sm' | 'md' | 'lg' | 'xl' | 'xxl';

interface IconProps {
  readonly name: UxIconName;
  readonly size?: IconSize;
  /** Only an icon that carries meaning alone gets a label; next to words it stays hidden from assistive technology. */
  readonly label?: string;
  readonly className?: string | undefined;
}

export function Icon({ name, size = 'lg', label, className }: IconProps) {
  const Glyph = ICONS[name];
  const classes = [styles.icon, className].filter(Boolean).join(' ');
  return label ? (
    <Glyph
      role="img"
      aria-label={label}
      className={classes}
      data-size={size}
      strokeWidth={1.75}
      focusable="false"
    />
  ) : (
    <Glyph aria-hidden="true" className={classes} data-size={size} strokeWidth={1.75} focusable="false" />
  );
}
