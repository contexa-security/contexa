package io.contexa.autoconfigure.hostredis;

import org.springframework.data.annotation.Id;
import org.springframework.data.redis.core.RedisHash;

/**
 * A device a host application keeps in Redis through a Spring Data repository of its own, which Spring Boot makes from the
 * application's packages.
 */
@RedisHash("host-devices")
public class HostDevice {

    @Id
    private String id;

    private String label;

    public HostDevice() {
    }

    public HostDevice(String id, String label) {
        this.id = id;
        this.label = label;
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getLabel() {
        return label;
    }

    public void setLabel(String label) {
        this.label = label;
    }
}
